<?php

namespace Pop\Pdf\Test\Build\Html\Form;

use Pop\Pdf\Build\Html\Parser;
use PHPUnit\Framework\TestCase;

class LayoutTest extends TestCase
{

    public function testFormProducesNamedDocumentFormAndFields()
    {
        $html = '<html><body><form id="contact">' .
            '<label>Name:</label><input type="text" name="name" value="Jane">' .
            '<textarea name="bio">Hello</textarea>' .
            '<select name="country"><option value="us">United States</option><option value="ca">Canada</option></select>' .
            '<input type="checkbox" name="agree" checked>' .
            '<button type="submit">Send</button>' .
            '</form></body></html>';

        $parser = Parser::parseString($html);
        $document = $parser->process();

        $this->assertNotNull($document->getForm('contact'));

        $page = $document->getPage(1);
        $this->assertTrue($page->hasFields());

        $fieldNames = array_map(fn ($f) => $f['field']->getName(), $page->getFields());
        $this->assertContains('name', $fieldNames);
        $this->assertContains('bio', $fieldNames);
        $this->assertContains('country', $fieldNames);
        $this->assertContains('agree', $fieldNames);
    }

    public function testBareInputWithNoFormAncestorStillConverts()
    {
        $html = '<html><body><input type="text" name="loose"></body></html>';

        $parser = Parser::parseString($html);
        $document = $parser->process();

        $page = $document->getPage(1);
        $this->assertTrue($page->hasFields());
        $fieldNames = array_map(fn ($f) => $f['field']->getName(), $page->getFields());
        $this->assertContains('loose', $fieldNames);
    }

    public function testRadioButtonsShareFieldNameAndCarryValue()
    {
        $html = '<html><body><form id="survey">' .
            '<input type="radio" name="plan" value="a" checked>' .
            '<input type="radio" name="plan" value="b">' .
            '</form></body></html>';

        $parser = Parser::parseString($html);
        $document = $parser->process();

        $page = $document->getPage(1);
        $radios = array_filter($page->getFields(), fn ($f) => $f['field']->getName() === 'plan');
        $this->assertCount(2, $radios);
        foreach ($radios as $radio) {
            $this->assertTrue($radio['field']->isRadio());
        }
    }

    public function testMissingNameAttributeGetsAutoGeneratedName()
    {
        $html = '<html><body><form id="noname"><input type="text"></form></body></html>';

        $parser = Parser::parseString($html);
        $document = $parser->process();

        $page = $document->getPage(1);
        $this->assertTrue($page->hasFields());
        $this->assertNotNull($page->getFields()[0]['field']->getName());
    }
}
